export function rootSupportGeometry(THREE, spec, bottom = spec.bottomOffset ?? -0.03, top = 0.2) {
  const points = spec.polygon,
    n = points.length,
    positions = [],
    indices = [];
  for (const y of [spec.base + bottom, spec.base + top]) for (const [x, z] of points) positions.push(x, y, z);
  for (const tri of THREE.ShapeUtils.triangulateShape(
    points.map(p => new THREE.Vector2(p[0], p[1])),
    []
  )) {
    let [a, b, c] = tri;
    const A = points[a],
      B = points[b],
      C = points[c];
    if ((B[0] - A[0]) * (C[1] - A[1]) - (B[1] - A[1]) * (C[0] - A[0]) < 0) [b, c] = [c, b];
    indices.push(a, b, c, n + a, n + c, n + b);
  }
  for (let i = 0; i < n; i++) {
    const j = (i + 1) % n;
    indices.push(i, n + i, j, j, n + i, n + j);
  }
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute('position', new THREE.Float32BufferAttribute(positions, 3));
  geometry.setIndex(indices);
  geometry.computeVertexNormals();
  return geometry;
}
